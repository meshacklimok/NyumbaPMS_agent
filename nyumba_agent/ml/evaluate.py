"""Time-split evaluation of the late-payment model. Writes docs/08_LATE_MODEL_EVALUATION.md.

    python -m nyumba_agent.ml.evaluate
"""

from pathlib import Path

from .. import config, db
from . import late_model

OUT = config.ROOT / "docs" / "08_LATE_MODEL_EVALUATION.md"


def render(r: dict) -> str:
    t, s, p = r["table"], r["sizes"], r["periods"]
    rows = "\n".join(
        f"| {name} | {v['precision']:.2f} | {v['recall']:.2f} | {v['f1']:.2f} | {v['accuracy']:.2f} | "
        + (f"{v['roc_auc']:.2f} | {v['pr_auc']:.2f} |" if "roc_auc" in v else "n/a | n/a |")
        for name, v in t.items())
    m, last = t["logistic regression"], t["late if late last month"]
    if r["beats_baselines"]:
        verdict = "The model beats both baselines on F1 on the held-out months."
    else:
        verdict = (f"**The model does not beat both baselines.** Its F1 ({m['f1']:.2f}) is not above the "
                   f"'late last month' rule ({last['f1']:.2f}); it beats 'always on-time' only because that baseline "
                   f"never flags anyone (recall 0). Its ranking quality is modest (ROC AUC {m['roc_auc']:.2f}, "
                   f"PR AUC {m['pr_auc']:.2f} against a late rate of {r['late_rate']['test']:.2f}).")
    drivers = "\n".join(f"- `{n}`: {c:+.2f}" for n, c in r["coefficients"][:8])
    return f"""# Late-payment model: evaluation

Generated by `python -m nyumba_agent.ml.evaluate` on the synthetic database (seed 42). Do not edit by hand.

## Setup
- Unit of prediction: one invoice. Label: paid in full after due date + {config.GRACE_DAYS} days, or still unpaid.
- Features: only the tenant's earlier invoices, seen as of the invoice's period start (before its due date), plus rent,
  rent against list rent, tenure, employment, property category and calendar month. No payment made after the as-of
  date can reach a feature (tested in `tests/test_late_model.py`).
- Model: logistic regression (balanced class weights). Decision threshold {r['threshold']:.2f}, chosen on a validation slice.
- Time split: train {s['train']} invoices up to {p['train_to']}; validation {s['valid']} (next 3 months, threshold only);
  test {s['test']} invoices, {p['test_from']} to {p['test_to']}. The final fit uses train + validation.
- Late rate: train {r['late_rate']['train']:.2f}, test {r['late_rate']['test']:.2f}.

## Results on the newest months (late = positive class)

| Predictor | Precision | Recall | F1 | Accuracy | ROC AUC | PR AUC |
|---|---|---|---|---|---|---|
{rows}

{verdict}

## Largest model coefficients (standardised inputs)
{drivers}

## Caveats
- **The data is synthetic.** Lateness was generated from a hidden reliability trait, a seasonal bump and
  noise by our own generator, so these scores say how well the pipeline works, not how it would do on real tenants.
  Real data may score higher or lower.
- The test set is small ({s['test']} invoices); differences of a few F1 points are within noise.
- Accuracy flatters 'always on-time' because most invoices are on time. Judge by precision, recall and F1 on the late class.
- Labels for recent invoices treat 'unpaid so far' as late, which can overstate lateness for the newest months.
- Features were chosen using the validation slice only; the test months were scored once per run.
"""


def main():
    conn = db.connect_ro()
    try:
        result = late_model.evaluate(late_model.training_frame(conn))
    finally:
        conn.close()
    OUT.write_text(render(result))
    print(f"wrote {OUT}\nbeats both baselines: {result['beats_baselines']}")


if __name__ == "__main__":
    main()
